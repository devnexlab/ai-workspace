AGE_MAP = {a['key']: a for a in AGE_BANDS}


def list_age_bands():
    return list(AGE_BANDS)


def keywords_for_ages(age_keys=None, include_insurance=False):
    """展开年龄段关键词列表。"""
    keys = age_keys or [a['key'] for a in AGE_BANDS]
    out = []
    for k in keys:
        band = AGE_MAP.get(k)
        if band:
            out.extend(band['keywords'])
    if include_insurance:
        out.extend(INSURANCE_KEYWORDS)
    # 去重保序
    seen = set()
    uniq = []
    for w in out:
        if w not in seen:
            seen.add(w)
            uniq.append(w)
    return uniq


def guess_age_band(title, keyword=''):
    """根据标题/关键词粗分年龄段。"""
    text = f'{title} {keyword}'
    rules = [
        ('20s', ['00后', '大学生', '租房', '恋爱', '第一份工作', '年轻人', '职场新人']),
        ('30s', ['宝妈', '二胎', '房贷', '育儿', '30岁', '夫妻', '带娃']),
        ('40s', ['四十', '中年', '赡养', '体检', '事业']),
        ('50s', ['五十', '退休前', '更年期', '慢性病']),
        ('60s', ['六十', '养老金', '退休', '隔代', '防骗', '医保']),
        ('80s', ['八十', '八旬', '陪护', '老花', '听力', '居家养老安全']),
        ('70s', ['七十', '老人', '保健品', '养老院', '就医']),
    ]
    for band, words in rules:
        if any(w in text for w in words):
            return band
    return 'all'
